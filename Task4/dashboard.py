def build_network_line(network: pd.DataFrame, protocol_filter: str) -> go.Figure:
    """Build Chart 1: Network Throughput line chart with anomaly highlights.

    Features a Plotly dropdown via the filter argument (protocol_filter)
    which is driven by the Dash callback. Anomalous data points are plotted
    as large red markers on top of the line.

    Args:
        network:         Full network traffic DataFrame.
        protocol_filter: Protocol string to filter by, or "All" for no filter.

    Returns:
        Plotly Figure object.
    """
    df = network.copy()
    if protocol_filter and protocol_filter != "All":
        df = df[df["protocol"] == protocol_filter]

    # Separate normal and anomaly rows for layered plotting
    normal  = df[df["anomaly_flag"] == 0]
    anomaly = df[df["anomaly_flag"] == 1]

    fig = go.Figure()

    # Main throughput line
    fig.add_trace(go.Scatter(
        x=df["timestamp"], y=df["throughput_mbps"],
        mode="lines+markers",
        name="Throughput",
        line=dict(color=COLOR_BLUE, width=2),
        marker=dict(size=5, color=COLOR_BLUE),
        hovertemplate="<b>%{x}</b><br>Throughput: %{y:.1f} Mbps<extra></extra>",
    ))

    # Anomaly overlay — large red markers
    if not anomaly.empty:
        fig.add_trace(go.Scatter(
            x=anomaly["timestamp"], y=anomaly["throughput_mbps"],
            mode="markers",
            name="Anomaly",
            marker=dict(size=14, color=COLOR_RED, symbol="x", line=dict(width=2, color="white")),
            hovertemplate="<b>ANOMALY</b><br>%{x}<br>Throughput: %{y:.1f} Mbps<extra></extra>",
        ))

    fig.update_layout(
        title=dict(text="Network Throughput Over Time", font=dict(color=COLOR_TEXT, size=16)),
        xaxis=dict(title="Timestamp", color=COLOR_TEXT, gridcolor="#2c2c44"),
        yaxis=dict(title="Throughput (Mbps)", color=COLOR_TEXT, gridcolor="#2c2c44"),
        paper_bgcolor=COLOR_CARD,
        plot_bgcolor=COLOR_BG,
        font=dict(color=COLOR_TEXT),
        legend=dict(bgcolor=COLOR_CARD, bordercolor="#444"),
        margin=dict(l=50, r=20, t=50, b=50),
    )
    return fig


def build_geo_map(network: pd.DataFrame) -> go.Figure:
    """Build Chart 2: Geo-spatial scatter map of network traffic sources.

    Each point represents one network session. Colour encodes anomaly status
    (red = anomaly, green = normal) and size encodes throughput volume.

    Args:
        network: Full network traffic DataFrame.

    Returns:
        Plotly Figure object.
    """
    df = network.copy()
    df["anomaly_label"] = df["anomaly_flag"].map({0: "Normal", 1: "Anomaly"})
    df["colour"]        = df["anomaly_flag"].map({0: COLOR_GREEN, 1: COLOR_RED})

    fig = px.scatter_geo(
        df,
        lat="src_lat",
        lon="src_lon",
        color="anomaly_label",
        color_discrete_map={"Normal": COLOR_GREEN, "Anomaly": COLOR_RED},
        size="throughput_mbps",
        size_max=30,
        hover_data={
            "src_ip":          True,
            "protocol":        True,
            "throughput_mbps": ":.1f",
            "anomaly_label":   True,
            "src_lat":         False,
            "src_lon":         False,
        },
        projection="natural earth",
        title="Global Network Traffic Sources",
    )

    fig.update_layout(
        paper_bgcolor=COLOR_CARD,
        font=dict(color=COLOR_TEXT),
        title=dict(font=dict(color=COLOR_TEXT, size=16)),
        geo=dict(
            bgcolor=COLOR_BG,
            landcolor="#2c3e50",
            oceancolor="#1a1a2e",
            showocean=True,
            showland=True,
            showcountries=True,
            countrycolor="#444",
            framecolor="#444",
        ),
        legend=dict(bgcolor=COLOR_CARD, bordercolor="#444", font=dict(color=COLOR_TEXT)),
        margin=dict(l=10, r=10, t=50, b=10),
    )
    return fig


def build_endpoint_bar(endpoints: pd.DataFrame) -> go.Figure:
    """Build Chart 3: Stacked bar chart of endpoint security status.

    Shows firewall, antivirus, and disk encryption status per hostname
    using traffic-light colour coding (red/amber/green).

    Args:
        endpoints: Endpoints DataFrame.

    Returns:
        Plotly Figure object.
    """
    df = endpoints.copy()

    # Encode each status as a numeric risk score for stacking height
    fw_colour  = df["firewall_status"].map({"Active": COLOR_GREEN, "Inactive": COLOR_RED})
    av_colour  = df["antivirus_status"].map({"Updated": COLOR_GREEN, "Outdated": COLOR_AMBER, "Missing": COLOR_RED})
    enc_colour = df["disk_encryption"].map({"Enabled": COLOR_GREEN, "Disabled": COLOR_RED})

    # One bar per metric per host, colour-coded by status
    fig = go.Figure()

    fw_colors  = df["firewall_status"].map({"Active": COLOR_GREEN, "Inactive": COLOR_RED}).tolist()
    av_colors  = df["antivirus_status"].map({"Updated": COLOR_GREEN, "Outdated": COLOR_AMBER, "Missing": COLOR_RED}).tolist()
    enc_colors = df["disk_encryption"].map({"Enabled": COLOR_GREEN, "Disabled": COLOR_RED}).tolist()

    fig.add_trace(go.Bar(
        name="Firewall",
        x=df["hostname"],
        y=[1] * len(df),
        marker_color=fw_colors,
        hovertext=df["firewall_status"],
        hovertemplate="<b>%{x}</b><br>Firewall: %{hovertext}<extra></extra>",
    ))
    fig.add_trace(go.Bar(
        name="Antivirus",
        x=df["hostname"],
        y=[1] * len(df),
        marker_color=av_colors,
        hovertext=df["antivirus_status"],
        hovertemplate="<b>%{x}</b><br>Antivirus: %{hovertext}<extra></extra>",
    ))
    fig.add_trace(go.Bar(
        name="Disk Encryption",
        x=df["hostname"],
        y=[1] * len(df),
        marker_color=enc_colors,
        hovertext=df["disk_encryption"],
        hovertemplate="<b>%{x}</b><br>Encryption: %{hovertext}<extra></extra>",
    ))

    fig.update_layout(
        barmode="stack",
        title=dict(text="Endpoint Security Status Overview", font=dict(color=COLOR_TEXT, size=16)),
        xaxis=dict(title="Hostname", color=COLOR_TEXT, gridcolor="#2c2c44"),
        yaxis=dict(title="Status Layers", color=COLOR_TEXT, gridcolor="#2c2c44", showticklabels=False),
        paper_bgcolor=COLOR_CARD,
        plot_bgcolor=COLOR_BG,
        font=dict(color=COLOR_TEXT),
        legend=dict(bgcolor=COLOR_CARD, bordercolor="#444"),
        margin=dict(l=50, r=20, t=50, b=80),
    )
    return fig


def build_backup_gauge(backups: pd.DataFrame) -> go.Figure:
    """Build Chart 4a: Gauge chart showing average backup coverage.

    Colour zones: 0–60 red (critical), 60–80 amber (warning),
    80–100 green (good).

    Args:
        backups: Backups DataFrame.

    Returns:
        Plotly Figure object.
    """
    avg_coverage = round(backups["coverage_pct"].mean(), 1)

    fig = go.Figure(go.Indicator(
        mode="gauge+number+delta",
        value=avg_coverage,
        delta={"reference": 80, "valueformat": ".1f"},
        number={"suffix": "%", "font": {"color": COLOR_TEXT}},
        gauge={
            "axis":      {"range": [0, 100], "tickcolor": COLOR_TEXT},
            "bar":       {"color": COLOR_BLUE},
            "bgcolor":   COLOR_BG,
            "bordercolor": "#444",
            "steps": [
                {"range": [0,  60], "color": COLOR_RED},
                {"range": [60, 80], "color": COLOR_AMBER},
                {"range": [80, 100], "color": COLOR_GREEN},
            ],
            "threshold": {
                "line": {"color": "white", "width": 3},
                "thickness": 0.85,
                "value": 80,
            },
        },
        title={"text": "Average Backup Coverage", "font": {"color": COLOR_TEXT, "size": 14}},
    ))

    fig.update_layout(
        paper_bgcolor=COLOR_CARD,
        font=dict(color=COLOR_TEXT),
        margin=dict(l=30, r=30, t=60, b=20),
        height=280,
    )
    return fig


def build_backup_pie(backups: pd.DataFrame) -> go.Figure:
    """Build Chart 4b: Pie chart of backup validation results (Pass vs Fail).

    Args:
        backups: Backups DataFrame.

    Returns:
        Plotly Figure object.
    """
    counts = backups["validation_result"].value_counts().reset_index()
    counts.columns = ["result", "count"]
    colour_map = {"Pass": COLOR_GREEN, "Fail": COLOR_RED}

    fig = px.pie(
        counts,
        names="result",
        values="count",
        color="result",
        color_discrete_map=colour_map,
        title="Backup Validation Results",
        hole=0.35,
    )
    fig.update_traces(textfont_color=COLOR_TEXT)
    fig.update_layout(
        paper_bgcolor=COLOR_CARD,
        font=dict(color=COLOR_TEXT),
        title=dict(font=dict(color=COLOR_TEXT, size=14)),
        legend=dict(bgcolor=COLOR_CARD, bordercolor="#444", font=dict(color=COLOR_TEXT)),
        margin=dict(l=20, r=20, t=60, b=20),
        height=280,
    )
    return fig


