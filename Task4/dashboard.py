# Data loading helpers
# ─────────────────────────────────────────────────────────────────────────────

def load_data() -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Load all four CSV datasets from disk.

    Called on initial load and every 30 seconds by the auto-refresh callback.

    Returns:
        Tuple of (network_df, endpoints_df, backups_df, staff_df).
    """
    network   = pd.read_csv(NETWORK_CSV,  parse_dates=["timestamp"])
    endpoints = pd.read_csv(ENDPOINT_CSV)
    backups   = pd.read_csv(BACKUP_CSV,   parse_dates=["backup_date"])
    staff     = pd.read_csv(STAFF_CSV)
    print(f"[dashboard] Data reloaded at {datetime.now().strftime('%H:%M:%S')}")
    return network, endpoints, backups, staff


