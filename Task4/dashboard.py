def calc_kpis(
    network: pd.DataFrame,
    endpoints: pd.DataFrame,
    backups: pd.DataFrame,
    staff: pd.DataFrame,
) -> dict:
    """Compute the four headline KPI values for the summary cards.

    Args:
        network:   Network traffic DataFrame.
        endpoints: Endpoints DataFrame.
        backups:   Backups DataFrame.
        staff:     Staff readiness DataFrame.

    Returns:
        Dictionary with keys: anomalies, endpoint_issues,
        backup_coverage, high_risk_staff.
    """
    return {
        "anomalies":        int(network["anomaly_flag"].sum()),
        "endpoint_issues":  int((endpoints["active_issues"] > 0).sum()),
        "backup_coverage":  round(backups["coverage_pct"].mean(), 1),
        "high_risk_staff":  int((staff["risk_profile"] == "High").sum()),
    }


