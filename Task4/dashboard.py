def make_kpi_card(title: str, value: str, colour: str) -> dbc.Card:
    """Build a single KPI summary card with coloured value text.

    Args:
        title:  Short label displayed below the value.
        value:  Formatted metric value shown prominently.
        colour: Hex colour string for the value text.

    Returns:
        A dash_bootstrap_components Card component.
    """
    return dbc.Card(
        dbc.CardBody([
            html.H2(value, style={"color": colour, "fontWeight": "bold", "marginBottom": "4px"}),
            html.P(title, style={"color": COLOR_TEXT, "fontSize": "0.85rem", "marginBottom": 0}),
        ]),
        style={
            "backgroundColor": COLOR_CARD,
            "border": f"1px solid {colour}",
            "borderRadius": "8px",
            "textAlign": "center",
            "padding": "4px",
        }
    )


